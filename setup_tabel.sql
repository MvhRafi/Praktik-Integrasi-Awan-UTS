-- ============================================================
-- SKRIP SETUP DATABASE SUPABASE: TANAMAN CURHAT (ZONA WAKTU WIB)
-- Berkas: setup_tabel.sql
-- ============================================================

-- Set zona waktu basis data / sesi ke WIB (Asia/Jakarta)
SET timezone = 'Asia/Jakarta';

-- 1. BUAT TABEL kondisi_tanaman
CREATE TABLE IF NOT EXISTS kondisi_tanaman (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dibuat_pada TIMESTAMPTZ DEFAULT NOW(), -- Menggunakan TIMESTAMPTZ agar mencakup offset +07:00
    kelembapan INT4 NOT NULL,
    cahaya INT4 NOT NULL,
    suasana_hati TEXT NOT NULL,
    curhatan TEXT NOT NULL
);

-- 2. BUAT TABEL perintah (Untuk Kendali Tombol "Siram")
CREATE TABLE IF NOT EXISTS perintah (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dibuat_pada TIMESTAMPTZ DEFAULT NOW(),
    aksi TEXT NOT NULL,             -- Contoh: "SIRAM"
    status TEXT DEFAULT 'PENDING'    -- Contoh: "PENDING" atau "DONE"
);

-- 3. AKTIFKAN ROW LEVEL SECURITY (RLS) - (Syarat Wajib UTS)
ALTER TABLE kondisi_tanaman ENABLE ROW LEVEL SECURITY;
ALTER TABLE perintah ENABLE ROW LEVEL SECURITY;

-- 4. BUAT POLICY RLS UNTUK TABEL kondisi_tanaman
CREATE POLICY "Izinkan Baca kondisi_tanaman" 
ON kondisi_tanaman FOR SELECT 
TO anon, authenticated 
USING (true);

CREATE POLICY "Izinkan Tambah kondisi_tanaman" 
ON kondisi_tanaman FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

-- 5. BUAT POLICY RLS UNTUK TABEL perintah
CREATE POLICY "Izinkan Baca perintah" 
ON perintah FOR SELECT 
TO anon, authenticated 
USING (true);

CREATE POLICY "Izinkan Tambah perintah" 
ON perintah FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

CREATE POLICY "Izinkan Update perintah" 
ON perintah FOR UPDATE 
TO anon, authenticated 
USING (true) 
WITH CHECK (true);